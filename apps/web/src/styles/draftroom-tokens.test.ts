import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'
import { contrastRatio } from '@yelison/forma-ui'
import { describe, expect, it } from 'vitest'

/* `draftroom-tokens.css` is generated outside this repository and committed as it comes. These tests do not judge its
 * values; they check the promises the rest of the app relies on: it says it is generated, it leaves Forma UI's tokens
 * alone, it switches themes the way Forma UI does, and the text colours it adds are readable. (That it declares no
 * Forma UI token is checked, for every stylesheet at once, in `tokens.sync.test.ts`.) */

const stylesDirectory = import.meta.dirname
const require = createRequire(import.meta.url)
const packageTokens = readFileSync(require.resolve('@yelison/forma-ui/tokens.css'), 'utf8')
const productTokens = readFileSync(join(stylesDirectory, 'draftroom-tokens.css'), 'utf8')

const withoutComments = (css: string) => css.replace(/\/\*[\s\S]*?\*\//g, '')

const declarations = (body: string) =>
  [...body.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)].map(([, name = '', value = '']) => [name, value.trim()] as const)

interface Rule {
  /** The `@media` condition around the rule, or `''` at the top level. */
  readonly media: string
  readonly selector: string
  readonly tokens: ReadonlyMap<string, string>
}

/** The rules of a token stylesheet, one level of `@media` deep, which is all these files use. */
function rulesOf(css: string): Rule[] {
  const rules: Rule[] = []
  const pattern = /(?:@media\s*([^{]+)\{\s*)?([^{}@]+)\{([^}]*)\}/g
  for (const [, media = '', selector = '', body = ''] of withoutComments(css).matchAll(pattern)) {
    rules.push({ media: media.trim(), selector: selector.trim(), tokens: new Map(declarations(body)) })
  }
  return rules
}

const THEME_SELECTORS = {
  light: { media: '', selector: ':root' },
  dark: { media: '', selector: ":root[data-theme='dark']" },
} as const

/** Where a rule that declares colours applies: the same pair is how Forma UI and the product pick a theme. */
const colourContexts = (rules: readonly Rule[]) =>
  rules
    .filter((rule) => [...rule.tokens.keys()].some((name) => name.startsWith('--color-')))
    .map((rule) => `${rule.media} | ${rule.selector}`)
    .sort()

/** The value of every token in a theme: the light rule first, and for the dark theme its own rule over it. */
function resolvedTheme(theme: keyof typeof THEME_SELECTORS): Map<string, string> {
  const resolved = new Map<string, string>()
  for (const css of [packageTokens, productTokens]) {
    const rules = rulesOf(css)
    for (const context of theme === 'dark' ? [THEME_SELECTORS.light, THEME_SELECTORS.dark] : [THEME_SELECTORS.light]) {
      const rule = rules.find(({ media, selector }) => media === context.media && selector === context.selector)
      rule?.tokens.forEach((value, name) => resolved.set(name, value))
    }
  }
  return resolved
}

describe('draftroom-tokens.css', () => {
  it('starts with the header that says it is generated and must not be edited', () => {
    expect(productTokens).toMatch(/^\/\* Generated by [^\n]*\n[^]*?Do not edit by hand[^]*?\*\//)
  })

  it("applies its colours under the same theme selectors as Forma UI's", () => {
    const product = colourContexts(rulesOf(productTokens))

    expect(product.length).toBeGreaterThan(0)
    expect(new Set(product)).toEqual(new Set(colourContexts(rulesOf(packageTokens))))
  })

  describe('the colours of the dark theme', () => {
    const rules = rulesOf(productTokens)
    const colours = (rule: Rule | undefined) =>
      new Map([...(rule?.tokens ?? [])].filter(([name]) => name.startsWith('--color-')))
    const light = colours(rules.find(({ media, selector }) => media === '' && selector === ':root'))
    const darkBySystem = colours(rules.find(({ media }) => media === '(prefers-color-scheme: dark)'))
    const darkByChoice = colours(rules.find(({ selector }) => selector === ":root[data-theme='dark']"))

    it('are the same when the system asks for dark as when the person chooses it', () => {
      // The AA checks below read the chosen theme; this is what makes them true for the system one too.
      expect(darkByChoice.size).toBeGreaterThan(0)
      expect(darkBySystem).toEqual(darkByChoice)
    })

    it('declare the colour tokens the light theme declares, and no others', () => {
      expect(new Set(darkByChoice.keys())).toEqual(new Set(light.keys()))
    })
  })
})

describe('the text colours of the product, in both themes', () => {
  // AA for text of any size.
  const MINIMUM = 4.5
  const pairs = [
    { text: '--color-purple-ink', background: '--color-purple-bg' },
    { text: '--color-nav-ink', background: '--color-nav-selected' },
  ] as const

  const cases = (['light', 'dark'] as const).flatMap((theme) => pairs.map((pair) => ({ theme, ...pair })))

  it.each(cases)('$text on $background passes AA in the $theme theme', ({ theme, text, background }) => {
    const colours = resolvedTheme(theme)
    const ink = colours.get(text)
    const surface = colours.get(background)

    expect(ink, `${text} is declared`).toBeDefined()
    expect(surface, `${background} is declared`).toBeDefined()
    expect(contrastRatio(ink ?? '', surface ?? '')).toBeGreaterThanOrEqual(MINIMUM)
  })
})
